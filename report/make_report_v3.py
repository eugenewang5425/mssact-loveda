def sig(x):
    """把 ΔKappa 折算成 σ_seed 倍数（可分辨性判读的统一尺度）"""
    if x is None:
        return "—"
    n = abs(x) / SIGMA
    tag = "**可分辨**" if n >= 2 else ("弱" if n >= 1 else "不可分辨")
    return f"{x:+.4f}（{n:.2f}σ，{tag}）"


