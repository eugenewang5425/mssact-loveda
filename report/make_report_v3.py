    cr = CS.get("rows") or {}
    for t, nm in (("lgR_c256_center", "随机裁剪 vs 固定中心（256）"),
                  ("lgR_c384_rand", "384 vs 256 随机裁剪"),
                  ("lgR_c512_rand", "512 vs 256 随机裁剪")):
        if t in cr:
            rows.append((nm, cr[t]["delta"]))
    for d in (SV.get("deltas_in_sigma") or []):
        rows.append((f"模块/容量变体 `{d['tag']}`", d["delta"]))
    out = ["| 效应 | ΔKappa | σ 倍数 | 判读 |", "|---|---:|---:|---|"]
    seen = set()
    for name, d in sorted(rows, key=lambda x: -abs(x[1])):
        if name in seen:
            continue
        seen.add(name)
        n = abs(d) / SIGMA
        L = "**可分辨**" if n >= 2 else ("弱（1–2σ）" if n >= 1 else "不可分辨")
        out.append(f"| {name} | {d:+.4f} | {n:.2f}σ | {L} |")
    return "\n".join(out)


